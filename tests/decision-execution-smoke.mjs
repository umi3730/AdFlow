// Opt-in functional verification against a dedicated local API instance.
import assert from 'node:assert/strict';
import { mkdirSync, writeFileSync } from 'node:fs';
assert.equal(process.env.ADFLOW_IDEMPOTENCY_HTTP_TEST,'1');
process.env.NEXT_PUBLIC_ADFLOW_API_URL ??= 'http://127.0.0.1:18082';
const target=new URL(process.env.NEXT_PUBLIC_ADFLOW_API_URL);
assert.ok(['127.0.0.1','localhost','[::1]'].includes(target.hostname));
const {api,newClientID}=await import('../web/lib/api.ts');
const {setSession}=await import('../web/lib/auth-session.ts');
setSession(await api.login('admin','adflow-admin'));
const input={requestId:newClientID('same-request'),userId:'demo-auction-user',slotId:'game-home-banner'};
const results=await Promise.all(Array.from({length:32},()=>api.decide(input)));
assert.equal(results[0].matched,true);
for(const result of results)assert.deepEqual(result,results[0]);
assert.notEqual(results[0].reservationToken,input.requestId);
for(const changed of [{...input,userId:'demo-user-match'},{...input,slotId:'another-slot'}]) await assert.rejects(api.decide(changed),error=>error.status===409&&error.code==='request_id_conflict');
const before=await api.metrics(results[0].campaignId);
const event={eventId:newClientID('exposure'),requestId:input.requestId,campaignId:results[0].campaignId,creativeId:results[0].creativeId,type:'impression'};
await api.recordEvent(event);await api.recordEvent(event);
const after=await api.metrics(event.campaignId);assert.equal(after.impressions-before.impressions,1);
const temporary={runId:newClientID('bound-profile'),requestId:'one',slotId:input.slotId,profile:{userId:'user-0001',tags:['auction_demo','gaming_interest'],fields:{device:'android',score:'80'}}};
const first=await api.simulateDecision(temporary);
const equivalent={...temporary,profile:{...temporary.profile,tags:[...temporary.profile.tags].reverse()}};
assert.deepEqual(await api.simulateDecision(equivalent),first);
await assert.rejects(api.simulateDecision({...temporary,profile:{...temporary.profile,fields:{device:'ios',score:'80'}}}),error=>error.status===409&&error.code==='request_id_conflict');
const report={at:new Date().toISOString(),target:target.origin,concurrentIdenticalRequests:32,identicalResults:results.length,userAndSlotConflicts:409,inlineProfileConflict:409,reorderedTagsReplayed:true,duplicateExposureDelta:after.impressions-before.impressions,priceFen:results[0].pricing.priceFen};
mkdirSync('docs/verification/decision-execution',{recursive:true});
writeFileSync('docs/verification/decision-execution/http-smoke.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
