export function creativeImageURL(input: string, origin: string) {
  const text = input.trim();
  const url =
    text.startsWith('/') && !text.startsWith('//')
      ? new URL(text, origin)
      : new URL(text);
  if (!['http:', 'https:'].includes(url.protocol))
    throw new Error('素材图片仅支持 HTTP 或 HTTPS 地址');
  return url.href;
}

export function localCreativeImageURL(assetID: string, origin: string) {
  const asset = demoCreatives.find((item) => item.id === assetID);
  if (!asset) throw new Error('请选择本地素材库中的图片');
  return creativeImageURL(asset.path, origin);
}

export function isDemoCreative(input: string) {
  try {
    return demoCreatives.some(
      (asset) => asset.path === new URL(input, 'http://local.test').pathname,
    );
  } catch {
    return false;
  }
}

export function displayCreativeURL(input: string) {
  try {
    const url = new URL(input);
    if (
      url.origin === 'https://adflow.invalid' &&
      !url.username &&
      !url.password &&
      !url.search &&
      !url.hash &&
      demoCreatives.some((asset) => asset.path === url.pathname)
    )
      return url.pathname;
  } catch {}
  return input;
}
